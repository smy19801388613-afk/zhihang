const browser = { fill: async () => ({ evidence: '' }), submit: async () => ({ evidence: '', receipt: '' }) };
test('resegmentation preview preserves confirmations until explicit replacement and retains history', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, experienceText: '校园经历\n2024.09—2025.06  学生会外联部｜小组长\n负责赞助沟通和资料整理。\n\n项目经历\n2025.03—2025.06  市场研究课程项目｜成员\n负责访谈同学并整理课程报告。', facts: [{ id: 'old', text: '原来已确认的整段经历', source: '原文', confirmed: true }] };
  state.resumes = [{ id: 'history', version: 1, createdAt: '2026-01-01', profile: structuredClone(state.profile), job: state.job, bullets: [], rationale: '', approved: true, stale: false }];
  store.save(state, state.revision);
  const workflow = new Workflow(store, createModelEngine({}), browser);
  let next = await workflow.act({ type: 'preview_fact_split', expectedRevision: store.read().revision });
  assert.deepEqual(next.profile.facts, state.profile.facts);
  assert.ok(next.factPreview!.facts.length >= 2);
  assert.ok(next.factPreview!.facts.every(fact => !fact.confirmed));
  const scoped = next.factPreview!.facts.find(fact => fact.text.includes('外联部'))!;
  assert.doesNotMatch(scoped.text, /课程项目/);
  next = await workflow.act({ type: 'discard_fact_split', expectedRevision: next.revision });
  assert.equal(next.factPreview, null); assert.deepEqual(next.profile.facts, state.profile.facts);
  next = await workflow.act({ type: 'preview_fact_split', expectedRevision: next.revision });
  next = await workflow.act({ type: 'apply_fact_split', expectedRevision: next.revision });
  assert.ok(next.profile.facts.every(fact => !fact.confirmed)); assert.equal(next.resumes[0].stale, true);
  assert.deepEqual(next.resumes[0].profile, state.resumes[0].profile, 'The existing resume snapshot remains immutable');
});
test('live reorganization previews the agent result without replacing facts and persists its provenance only on apply', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, facts: [{ id: 'old', text: '原有确认事实', source: '原文', confirmed: true }] };
  store.save(state, state.revision);
  let calls = 0;
  const organized = { id: 'new', text: '提炼后的事实', source: '原始材料', sourceQuotes: ['原始材料'], confirmed: false, experience: { id: 'child', title: '系统子项目', parentId: 'parent', parentTitle: '咨询服务项目', kind: 'project' as const }, reviewNote: '需要确认具体职责' };
  const engine = { ...createModelEngine({}), mode: 'live' as const, extractProfile: async () => { calls++; return { facts: [organized], questions: ['请核对职责'], agentRun: { version: 1 as const, kind: 'experience' as const, model: 'test-model', reviewed: true, passes: 2, warnings: [] } }; } };
  const workflow = new Workflow(store, engine, browser);
  const preview = await workflow.act({ type: 'preview_fact_split', expectedRevision: store.read().revision });
  assert.equal(calls, 1); assert.deepEqual(preview.profile.facts, state.profile.facts);
  assert.equal(preview.factOrganization, undefined); assert.equal(preview.factPreview!.agentRun!.reviewed, true);
  const applied = await workflow.act({ type: 'apply_fact_split', expectedRevision: preview.revision });
  assert.deepEqual(applied.profile.facts, [organized]); assert.equal(applied.factOrganization!.model, 'test-model');
  assert.equal(applied.factPreview, null);
});
test('an agent reorganization failure leaves all existing confirmations and snapshots untouched', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, facts: [{ id: 'saved', text: '已确认内容', source: '用户', confirmed: true }] };
  store.save(state, state.revision);
  const before = store.read();
  const engine = { ...createModelEngine({}), mode: 'live' as const, extractProfile: async () => { throw new Error('有限复核未通过'); } };
  await assert.rejects(new Workflow(store, engine, browser).act({ type: 'preview_fact_split', expectedRevision: before.revision }), /有限复核/);
  assert.deepEqual(store.read(), before);
});
test('finishing exploration and clearing history retain saved jobs, profile and resumes', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, major: '', facts: [] };
  const engine = createCareerEngine({}, { search: async () => ({ sources: [], warning: undefined }) });
  const reply = await engine.chat(state.profile, [{ role: 'user', content: '我的专业能做什么' }], []);
  state.exploration!.directions = reply.directions;
  state.exploration!.messages = [{ role: 'user', content: 'old history' }];
  state.exploration!.companies = [{ id: 'saved', name: '示例', industry: '互联网', role: '运营', rationale: '', requirements: [], sourceLabel: '浏览器导入', sourceKind: 'browser_capture', careerUrl: 'https://example.com/job', checkedAt: '2026-01-01', hiringStatus: 'unverified', selected: true, decision: 'like' }];
  store.save(state, state.revision);
  const workflow = new Workflow(store, createModelEngine({}), browser, engine);
  let next = await workflow.act({ type: 'finish_career_chat', expectedRevision: store.read().revision });
  assert.equal(next.exploration!.conversationPhase, 'ready');
  next = await workflow.act({ type: 'clear_career_chat', expectedRevision: next.revision });
  assert.deepEqual(next.exploration!.messages, []); assert.deepEqual(next.exploration!.directions, []);
  assert.deepEqual(next.exploration!.companies, state.exploration!.companies);
  assert.deepEqual(next.profile, state.profile);
});
test('chat attachment context is model input only and never silently changes confirmed facts', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, major: '', facts: [{ id: 'fact', text: '确认的课程经历', source: '用户原文', confirmed: true }] }; store.save(state, state.revision);
  const attachments = new CareerAttachments();
  const file = await attachments.add({ name: '参考岗位.txt', mimeType: 'text/plain', buffer: Buffer.from('参考资料中说曾主导企业项目，这不是个人已确认事实。') }, false);
  let received: CareerChatContext | undefined;
  const career = { ...createCareerEngine({}), chat: async (_profile: unknown, _messages: unknown, _directions: unknown, context?: CareerChatContext) => { received = context; return { message: '附件是参考材料，不能据此认定你有企业经验。', directions: [], conversationPhase: 'explore' as const }; } };
  const workflow = new Workflow(store, createModelEngine({}), browser, career, undefined, undefined, attachments);
  const next = await workflow.act({ type: 'career_chat', message: '请分析附件', attachmentIds: [file.id], expectedRevision: store.read().revision });
  assert.match(received!.attachments![0].text!, /参考资料/);
  assert.deepEqual(next.profile, state.profile); assert.equal(next.exploration!.messages[0].attachments![0].name, '参考岗位.txt');
  assert.throws(() => attachments.resolve([file.id]), /过期/, 'Successful send releases the pending attachment');
});
test('changing direction in chat or selection preserves liked companies', async t => {
  const store = new Store(':memory:'); t.after(() => store.close());
  const state = store.read(); state.profile = { ...exampleProfile, facts: [] };
  const original = { id: 'a', industry: '互联网', role: '资料研究', rationale: '', transferableSkills: [], gaps: [], entryRequirements: '', salaryContext: '' };
  state.exploration!.directions = [original]; state.exploration!.selectedDirectionIds = ['a'];
  state.exploration!.companies = [{ id: 'saved', name: '已保存公司', industry: '互联网', role: '运营', rationale: '', requirements: [], sourceLabel: '公司探索', careerUrl: 'https://example.com/job', checkedAt: '2026-01-01', hiringStatus: 'unverified', selected: true, decision: 'like' }];
  store.save(state, state.revision);
  const career = { ...createCareerEngine({}), chat: async () => ({ message: '已切换方向', directions: [{ ...original, id: 'b', industry: '制造业' }] }) };
  const workflow = new Workflow(store, createModelEngine({}), browser, career);
  let next = await workflow.act({ type: 'career_chat', message: '我想改成制造业', expectedRevision: store.read().revision });
  assert.deepEqual(next.exploration!.selectedDirectionIds, []);
  assert.deepEqual(next.exploration!.companies, state.exploration!.companies);
  next = await workflow.act({ type: 'select_directions', directionIds: ['b'], expectedRevision: next.revision });
  assert.deepEqual(next.exploration!.companies, state.exploration!.companies);
});
